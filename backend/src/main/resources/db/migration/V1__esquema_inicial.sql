CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL, apellidos VARCHAR(100) NOT NULL DEFAULT '',
 email VARCHAR(150) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 rol VARCHAR(20) NOT NULL CHECK (rol IN ('admin','vendedor','cliente')),
 run VARCHAR(15) NOT NULL DEFAULT '', fecha_nacimiento VARCHAR(10) NOT NULL DEFAULT '',
 region VARCHAR(100) NOT NULL DEFAULT '', comuna VARCHAR(100) NOT NULL DEFAULT '',
 direccion VARCHAR(300) NOT NULL DEFAULT '', activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL, padre_id BIGINT REFERENCES categorias(id),
 CONSTRAINT categoria_no_autopadre CHECK (padre_id IS NULL OR padre_id <> id)
);
CREATE TABLE productos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 codigo VARCHAR(60) NOT NULL UNIQUE, nombre VARCHAR(150) NOT NULL, marca VARCHAR(100) NOT NULL,
 descripcion VARCHAR(2000) NOT NULL, imagen VARCHAR(2000) NOT NULL,
 precio NUMERIC(14,0) NOT NULL CHECK (precio > 0), stock INTEGER NOT NULL CHECK (stock >= 0),
 stock_critico INTEGER NOT NULL CHECK (stock_critico >= 0), categoria_id BIGINT NOT NULL REFERENCES categorias(id),
 destacado BOOLEAN NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE, version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE sesiones (
 id VARCHAR(36) PRIMARY KEY, usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 token_hash VARCHAR(64) NOT NULL UNIQUE, expira_en TIMESTAMP WITH TIME ZONE NOT NULL,
 revocada BOOLEAN NOT NULL DEFAULT FALSE, version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE pedidos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id), usuario VARCHAR(150) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL, estado VARCHAR(30) NOT NULL,
 nombre VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL, telefono VARCHAR(30) NOT NULL,
 tipo_entrega VARCHAR(20) NOT NULL, direccion VARCHAR(300) NOT NULL, comuna VARCHAR(100) NOT NULL,
 region VARCHAR(100) NOT NULL, metodo_pago VARCHAR(30) NOT NULL,
 subtotal NUMERIC(14,0) NOT NULL, costo_envio NUMERIC(14,0) NOT NULL, total NUMERIC(14,0) NOT NULL,
 clave_compra VARCHAR(150) NOT NULL UNIQUE, firma_compra VARCHAR(64) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE pedido_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 pedido_id BIGINT NOT NULL REFERENCES pedidos(id), producto_id BIGINT NOT NULL REFERENCES productos(id),
 nombre VARCHAR(150) NOT NULL, imagen VARCHAR(2000) NOT NULL,
 precio NUMERIC(14,0) NOT NULL, cantidad INTEGER NOT NULL CHECK (cantidad > 0)
);
CREATE TABLE consultas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL, email VARCHAR(150) NOT NULL, asunto VARCHAR(150) NOT NULL,
 comentario VARCHAR(3000) NOT NULL, fecha TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_pedidos_usuario ON pedidos(usuario_id);
CREATE INDEX idx_sesiones_usuario ON sesiones(usuario_id);
CREATE INDEX idx_productos_categoria ON productos(categoria_id);
